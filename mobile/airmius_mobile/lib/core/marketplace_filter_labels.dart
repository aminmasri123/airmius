String marketplaceFilterText(BuildContext context, String key) =>
    marketplaceFilterLabels[AirmiusScope.of(
      context,
    ).language.locale.languageCode]?[key] ??
    marketplaceFilterLabels['en']![key] ??
    key;

String marketplaceCategoryLabel(BuildContext context, String category) {
  final key = 'seller.category.$category';
  final translated = AirmiusScope.of(context).t(key);
  return translated == key ? category : translated;
}

