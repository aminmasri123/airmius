import 'package:flutter/widgets.dart';

enum AirmiusLanguage { de, en, fr, ar }

extension AirmiusLanguageMeta on AirmiusLanguage {
  String get code => switch (this) {
        AirmiusLanguage.de => 'DE',
        AirmiusLanguage.en => 'EN',
        AirmiusLanguage.fr => 'FR',
        AirmiusLanguage.ar => 'AR',
      };

  String get label => switch (this) {
        AirmiusLanguage.de => 'Deutsch',
        AirmiusLanguage.en => 'English',
        AirmiusLanguage.fr => 'Francais',
        AirmiusLanguage.ar => 'Arabic',
      };

  bool get isRtl => this == AirmiusLanguage.ar;

  Locale get locale => switch (this) {
        AirmiusLanguage.de => const Locale('de'),
        AirmiusLanguage.en => const Locale('en'),
        AirmiusLanguage.fr => const Locale('fr'),
        AirmiusLanguage.ar => const Locale('ar'),
      };
}

class AirmiusScope extends InheritedWidget {
  const AirmiusScope({
    super.key,
    required this.language,
    required this.setLanguage,
    required super.child,
  });

  final AirmiusLanguage language;
  final ValueChanged<AirmiusLanguage> setLanguage;

  static AirmiusScope of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<AirmiusScope>();
    assert(scope != null, 'AirmiusScope is missing');
    return scope!;
  }

  String t(String key) => _strings[language]?[key] ?? _strings[AirmiusLanguage.de]?[key] ?? key;

  String copy(String value) => _copy[language]?[value] ?? value;

  @override
  bool updateShouldNotify(AirmiusScope oldWidget) => language != oldWidget.language;
}

