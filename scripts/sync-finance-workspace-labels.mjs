import fs from 'node:fs'

const source = JSON.parse(fs.readFileSync('resources/js/i18n/clubFinanceWorkspaceLocalization.json', 'utf8'))
source.de = Object.fromEntries(Object.keys(source.en).map(key => [key, key]))
fs.writeFileSync('resources/js/i18n/clubFinanceWorkspaceLocalization.json', `${JSON.stringify(source, null, 2)}\n`)
const quote = value => JSON.stringify(value).replaceAll('$', '\\$')
const maps = Object.entries(source).map(([locale, labels]) =>
    `  ${quote(locale)}: {\n${Object.entries(labels).map(([key, value]) => `    ${quote(key)}: ${quote(value)},`).join('\n')}\n  },`).join('\n')
fs.writeFileSync('mobile/airmius_mobile/lib/core/club_finance_workspace_labels.dart',
    `// Generated by scripts/sync-finance-workspace-labels.mjs.\nconst Map<String, Map<String, String>> clubFinanceWorkspaceLabels = {\n${maps}\n};\n`)
